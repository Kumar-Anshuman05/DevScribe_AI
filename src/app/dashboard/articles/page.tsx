import Link from "next/link";
import { redirect } from "next/navigation";
import prisma from "@/lib/prisma";
import { createClient } from "@/lib/supabase/server";
import { Card, Badge, Button } from "@/components/ui";
import { FileText, BookOpen, Clock, Award, ArrowRight } from "lucide-react";

export const dynamic = "force-dynamic";

export default async function ArticlesListPage() {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    redirect("/login");
  }

  let articles: any[] = [];

  try {
    articles = await prisma.article.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: "desc" },
      include: {
        job: { select: { contentType: true, primaryLanguage: true, frameworks: true } },
      },
    });
  } catch (err) {
    console.warn("Prisma error loading articles list:", err);
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-border pb-6">
        <div>
          <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight">Article Library</h1>
          <p className="text-muted-foreground text-sm mt-1">
            Browse and inspect publication-grade technical blogs and tutorials generated by DevScribe AI.
          </p>
        </div>
        <Link href="/dashboard/generate">
          <Button size="sm">Generate New Article</Button>
        </Link>
      </div>

      {articles.length === 0 ? (
        <Card className="p-12 text-center max-w-lg mx-auto">
          <FileText className="h-10 w-10 text-muted-foreground mx-auto mb-3" />
          <h3 className="text-base font-semibold">No Articles Published</h3>
          <p className="text-xs text-muted-foreground mt-1 mb-4">
            Completed generation jobs will store validated articles, markdown, and quality reports here.
          </p>
          <Link href="/dashboard/generate">
            <Button size="sm">Launch Generation Studio</Button>
          </Link>
        </Card>
      ) : (
        <div className="grid gap-4">
          {articles.map((article) => (
            <Card key={article.id} className="p-5 hover:border-primary/50 transition-all">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                <div className="space-y-1.5 max-w-3xl">
                  <div className="flex wrap items-center gap-2">
                    <Badge variant="outline" className="text-[10px]">
                      {article.job?.contentType || "TECHNICAL"}
                    </Badge>
                    {article.job?.primaryLanguage && (
                      <Badge variant="default" className="text-[10px]">
                        {article.job.primaryLanguage}
                      </Badge>
                    )}
                    <span className="text-xs text-muted-foreground flex items-center gap-1">
                      <Clock className="h-3 w-3" />
                      {article.readingTimeMinutes} min read ({article.wordCount} words)
                    </span>
                  </div>

                  <h3 className="text-base font-bold tracking-tight hover:text-primary transition-colors">
                    <Link href={`/dashboard/articles/${article.slug}`}>
                      {article.title}
                    </Link>
                  </h3>

                  <p className="text-xs text-muted-foreground line-clamp-2">
                    {article.summary}
                  </p>
                </div>

                <div className="flex sm:flex-col items-end justify-between gap-3 shrink-0">
                  <Badge variant={article.qualityScore >= 85 ? "success" : "warning"} className="gap-1">
                    <Award className="h-3 w-3" />
                    Score: {article.qualityScore}/100
                  </Badge>

                  <Link href={`/dashboard/articles/${article.slug}`}>
                    <Button size="sm" variant="outline" className="gap-1">
                      Read Article <ArrowRight className="h-3 w-3" />
                    </Button>
                  </Link>
                </div>
              </div>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
